@tool
def get_repair_cost(service: str, devices: int = 1) -> str:
    """Get the total repair cost in rupees for a laptop repair service and number of devices.

    Args:
        service: Repair service name, e.g. "screen replacement", "battery replacement", "keyboard repair", or "os installation"
        devices: Number of laptops needing the repair (default is 1)
    """
    cost = SERVICES.get(service.lower().strip())
    if cost is None:
        return f"'{service}' is not a standard service. Available services: {', '.join(SERVICES)}."
    return f"{devices} x {service} = Rs {cost * devices}"

@tool
def check_repair_slot(day: str) -> str:
    """Check ByteFix Electronics Repair shop hours and technician availability for a day of the week, e.g. "saturday"."""
    status = TECHNICIAN_SLOTS.get(day.lower().strip())
    return f"{day.capitalize()}: {status}" if status else f"'{day}' is not a valid day of the week."

from typing import Literal
from pydantic import BaseModel, Field

class RepairBooking(BaseModel):
    """A laptop repair booking extracted from a customer's chat message."""
    name: str = Field(description="Customer's first name")
    service: Literal["screen replacement", "battery replacement", "keyboard repair", "os installation"] = Field(
        description="Standard laptop repair service"
    )
    devices: int = Field(description="Number of laptops to repair", ge=1)
    drop_date: str = Field(description="Drop-off day or date as stated by the customer, e.g. '24 Dec' or 'Monday'")
    urgent: bool = Field(description="True if the customer mentions urgent or priority handling")

booking_extractor = llm.with_structured_output(RepairBooking)

