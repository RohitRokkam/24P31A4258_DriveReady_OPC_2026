@tool
def log_repair_booking(name: str, service: str, devices: int, drop_date: str, urgent: bool) -> str:
    """Save a confirmed laptop repair booking to the ByteFix Repair Bookings Google Sheet.
    Use ONLY when the customer has provided their name, service, number of devices, and drop-off date."""
    try:
        booking = RepairBooking(
            name=name,
            service=service.lower().strip(),
            devices=devices,
            drop_date=drop_date,
            urgent=urgent
        )
    except Exception as e:
        return f"Could not save booking: {e}. Ask the customer to clarify."

    total = SERVICES[booking.service] * booking.devices
    ws_biz.append_row([
        booking.name,
        booking.service,
        booking.devices,
        booking.drop_date,
        "yes" if booking.urgent else "no",
        total
    ])
    return f"Saved booking: {booking.devices} x {booking.service} for {booking.name} on {booking.drop_date}, Total: Rs {total}."

