def run_tests(active_chain, path: str = "tests.csv") -> float:
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    passed = 0
    for row in rows:
        answer = active_chain.invoke({"history": [], "question": row["question"]})
        ok = row["must_include"].lower() in answer.lower()
        passed += int(ok)
        status = "PASS" if ok else "FAIL"
        print(f"{status} | {row['question']} -> {answer.strip()[:75]}")
    rate = passed / len(rows)
    print(f"\nPass Rate: {passed}/{len(rows)} ({rate:.0%})")
    return rate

