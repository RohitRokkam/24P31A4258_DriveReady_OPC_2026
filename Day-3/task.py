SERVICES = {
    "screen replacement": 3500,
    "battery replacement": 1800,
    "keyboard repair": 1200,
    "os installation": 600,
}

AVAILABLE_SLOTS = {
    "monday": True,
    "tuesday": True,
    "wednesday": True,
    "thursday": True,
    "friday": True,
    "saturday": True,
    "sunday": False,
}

def get_repair_cost(service: str, devices: int = 1) -> int:
    """Return the total repair price in rupees for a service on the ByteFix menu."""
    key = service.lower().strip()
    if key not in SERVICES:
        raise ValueError(f"Service '{service}' is not in our standard price list.")
    return SERVICES[key] * devices

def is_drop_off_open(day: str) -> str:
    """Check whether ByteFix Electronics Repair is open for drop-offs on a given day of the week."""
    key = day.lower().strip()
    if key not in AVAILABLE_SLOTS:
        return "Please provide a valid day of the week (Monday to Sunday)."
    return "Open 10:00 AM to 7:00 PM" if AVAILABLE_SLOTS[key] else "Closed on Sundays."

print(get_repair_cost("screen replacement", 1))
