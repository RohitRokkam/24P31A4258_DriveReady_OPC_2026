def log_call(func):
    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        result = func(*args, **kwargs)
        print(f"   [log] {func.__name__}{args} -> {result!r}")
        return result
    return wrapper

@log_call
def get_repair_cost(service: str, devices: int = 1) -> int:
    """Return the total repair cost in rupees for a given service and device count."""
    key = service.lower().strip()
    if key not in SERVICES:
        raise ValueError(f"'{service}' is not listed in our standard services.")
    return SERVICES[key] * devices

