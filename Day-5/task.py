@tool
def search_bytefix_faq(question: str) -> str:
    """Search ByteFix Electronics Repair policies and FAQs: warranty, diagnostics,
    turnaround time, express service, doorstep pickup/delivery, payment, advance,
    cancellation, data backup, supported devices, charger requirements, and motherboard repairs.
    Use for any policy or rule question, NOT for exact repair prices or daily shop hours."""
    results = faq_collection.query(query_texts=[question], n_results=3)
    return "\n".join(results["documents"][0])

