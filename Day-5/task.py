import csv

def run_signoff_tests(path: str = "tests.csv") -> None:
    with open(path, mode="r", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    passed = 0
    for idx, row in enumerate(rows):
        # Fresh thread_id per question so test runs stay independent
        answer = chat(f"eval_thread_{idx}", row["question"])
        ok = row["must_include"].lower() in answer.lower()
        passed += int(ok)
        status = "PASS" if ok else "FAIL"
        print(f"{status} | Q: {row['question']} --> A: {answer.strip()[:80]}")

    rate = passed / len(rows)
    print(f"\nFinal Single-Agent Pass Rate: {passed}/{len(rows)} ({rate:.0%})")
    if rate >= 0.80:
        print("Sign-off PASSED (>= 80%). Ready for Level 3 multi-agent workflows!")

run_signoff_tests()